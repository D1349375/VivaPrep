import assert from "node:assert/strict";
import {EventEmitter} from "node:events";
import {PassThrough} from "node:stream";
import {CliConversation,currentQuestionOutput} from "../server/cli-conversation.js";
assert.equal(currentQuestionOutput('```json\n{"candidateQuestion":"你怎麼驗證{輸入}？","questionFocus":"verification","dialogueAction":"follow_up","sourceRefs":[]}\n```').questionFocus,"verification");
assert.equal(currentQuestionOutput('cached data'),null);
const child=new EventEmitter();child.stdin=new PassThrough();child.stdout=new PassThrough();child.stderr=new PassThrough();child.kill=()=>{};
let spawned=0;const cli=new CliConversation({cliPath:"test",modelId:"test",schema:{},cwd:"test",timeoutMs:10000,spawnProcess:()=>{spawned++;return child;}});
const output=message=>child.stdout.write(JSON.stringify(message)+"\n");
const first=cli.generate("first");
output({event:"step_update",step_update:{tool_name:"finish",tool_info:{parameters:{candidateQuestion:"第一題"}}}});
output({event:"result",result:{status:"SUCCESS",structured_output:{candidateQuestion:"舊內容"}}});
assert.equal((await first).candidateQuestion,"第一題");
const second=cli.generate("second");
const rejected=assert.rejects(second,{code:"AGENT_INVALID_OUTPUT"});
output({event:"result",result:{status:"SUCCESS",structured_output:{candidateQuestion:"第一題"}}});
await rejected;
const third=cli.generate("third");
output({event:"step_update",step_update:{tool_name:"finish",tool_info:{parameters:{candidateQuestion:"第三題"}}}});
output({event:"result",result:{status:"SUCCESS"}});
assert.equal((await third).candidateQuestion,"第三題");
assert.equal(spawned,1,"Reuse the interview process across turns");
const pending=cli.generate("pending");const queued=cli.generate("queued");
const canceled=Promise.all([assert.rejects(pending,{code:"AGENT_UNAVAILABLE"}),assert.rejects(queued,{code:"AGENT_UNAVAILABLE"})]);
cli.close();await canceled;
console.log("PASS: CLI reuse, current-turn output, stale-output rejection, queued-job cleanup");
